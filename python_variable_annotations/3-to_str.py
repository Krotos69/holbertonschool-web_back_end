#!/usr/bin/env python3
"""
Module for converting a float to its string representation.
Provides to_str(n) which returns the string form of a float.
"""


def to_str(n: float) -> str:
    """
    Return the string representation of a float.

    Args:
        n (float): Float to convert.

    Returns:
        str: String representation of n.
    """
    return str(n)
