#!/usr/bin/env python3
"""
Module for a simple typed addition function.
Provides add(a, b) which returns the sum of two floats.
"""

def add(a: float, b: float) -> float:
    """
    Return the sum of two floats.

    Args:
        a (float): First number.
        b (float): Second number.

    Returns:
        float: The sum of a and b.
    """
    return a + b
